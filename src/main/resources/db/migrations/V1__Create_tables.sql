-- V1: Tabelas de funcionarios e de tarefas.
-- A coluna url_img existe no model, mas nenhuma tela usa foto ainda: o frontend
-- vai ser escrito separado, entao a coluna fica esperando o que vier dali.

CREATE TABLE tb_tarefas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    dificuldade VARCHAR(255)
);

CREATE TABLE tb_cadastro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(255),
    email VARCHAR(255) UNIQUE,
    url_img VARCHAR(255),
    cargo VARCHAR(255),
    idade INT NOT NULL,
    tarefa_id BIGINT,
    CONSTRAINT fk_cadastro_tarefas FOREIGN KEY (tarefa_id) REFERENCES tb_tarefas(id)
);
